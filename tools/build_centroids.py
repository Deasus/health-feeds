#!/usr/bin/env python3
"""Build feeds/_shared/centroids.py from CINDER Mobile's boundaries.json
(simplified Natural Earth 1:50m, public domain): one row per country and per
state/province (US, CA, AU) with the centre of its largest polygon's bbox, the
same rule as CinderKit's GeoIndex.stateCenter. Run from the repo root:

  python3 tools/build_centroids.py [path/to/boundaries.json]
"""
import json, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/Projects/CINDER-Mobile/CinderKit/Sources/CinderKit/Resources/Boundaries/boundaries.json')
d = json.load(open(src))

def centre(shape):
    best, area = None, -1
    for rings in shape['p']:
        outer = rings[0]
        xs, ys = outer[0::2], outer[1::2]
        a = (max(xs) - min(xs)) * (max(ys) - min(ys))
        if a > area:
            area, best = a, ((min(ys) + max(ys)) / 2, (min(xs) + max(xs)) / 2)
    return round(best[0], 3), round(best[1], 3)

countries = []
for c in d['countries']:
    lat, lng = centre(c)
    countries.append((c['n'], c['a'], c.get('c') or '', c.get('s') or '', lat, lng, [round(v, 2) for v in c['bb']]))
states = []
for s in d['states']:
    lat, lng = centre(s)
    states.append((s['n'], s['a'], s['k'], lat, lng))

out = os.path.join(os.path.dirname(__file__), '..', 'feeds', '_shared', 'centroids.py')
with open(out, 'w') as f:
    f.write('"""Generated by tools/build_centroids.py from Natural Earth 1:50m boundaries (public domain).\n'
            'COUNTRIES: (name, iso2, continent, subregion, lat, lng, [minLng, minLat, maxLng, maxLat])\n'
            'STATES: (name, code, countryIso2, lat, lng)  — US, CA, AU only.\n"""\n')
    f.write('COUNTRIES = [\n' + ''.join(f'    {json.dumps(list(c))},\n' for c in sorted(countries)) + ']\n\n')
    f.write('STATES = [\n' + ''.join(f'    {json.dumps(list(s))},\n' for s in sorted(states)) + ']\n')
print(f'{len(countries)} countries, {len(states)} states → {os.path.relpath(out)}')
print('COUNTRY NAMES:', '; '.join(c[0] for c in sorted(countries)))
